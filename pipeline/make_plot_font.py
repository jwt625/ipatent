"""Generate viewer/plot-font.js, the single-stroke font used by the plotter SVG export (viewer/plot-export.js).

Source: the `hersheytext` npm package 2.0.0 (https://registry.npmjs.org/hersheytext/-/hersheytext-2.0.0.tgz), unpacked:
    python3 -I pipeline/make_plot_font.py <unpacked>/package
- Latin: svg_fonts/HersheySans1.svg (EMS Hershey Sans 1-stroke; glyphs with M/L commands only).
- Greek and a few math signs: hersheytext.json raw Hershey fonts `greek`, `mathlow`, `scripts`.
Output units: 1/1000 em, y up, baseline 0, cap height 662; each glyph is [advance, [[x0, y0, x1, y1, ...], ...]].
Every character used in data/*/traces is checked; missing ones are listed.
"""

import glob
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
K = 31.5  # EMS units per raw Hershey unit (cap height 21 raw = 662 EMS)
SHIFT = 94.5  # EMS glyphs sit 3 raw units right of their advance box; centre them

GREEK = dict(zip("ΑΒΧΔΕΦΓΗΙΚΛΜΝΟΠΘΡΣΤΥΩΞΨΖ", "ABCDEFGHIKLMNOPQRSTUWXYZ"))
GREEK |= dict(zip("αβχδεφϕγηικλμµνοπθϑρστυωξψζ", "abcdeffghiklmmnopqqrstuwxyz"))
MATH = {"≠": ("mathlow", "?"), "√": ("mathlow", "b"), "∞": ("mathlow", "_"), "ℓ": ("scripts", "l"),
        "±": ("mathlow", "!")}  # the EMS plus-minus is drawn 0.5 em right of its advance box
DROP = ".,:;"  # source data draws these dots 3 raw units above the baseline (the dot of "!" sits on it)
ALIAS = {"−": "-", "′": "'", "″": '"', "‐": "-", "’": "'", "‘": "'"}


def polylines(d: str, fx, fy) -> list:
    # M/L with implicit repeats: "M2,11 L4,9 7,8 18,8"
    out, cur, cmd, nums = [], None, "M", []
    for tok in re.findall(r"[ML]|-?[\d.]+", d):
        if tok in "ML":
            cmd = tok
            continue
        nums.append(float(tok))
        if len(nums) < 2:
            continue
        p = [round(fx(nums[0])), round(fy(nums[1]))]
        nums = []
        if cmd == "M":
            cur = list(p)
            out.append(cur)
            cmd = "L"
        else:
            cur += p
    return [c for c in out if len(c) >= 4]


def main() -> None:
    pkg = Path(sys.argv[1])
    glyphs = {}
    svg = (pkg / "svg_fonts" / "HersheySans1.svg").read_text()
    for m in re.finditer(r"<glyph ([^>]*)/>", svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', m.group(1)))
        if "unicode" not in a:
            continue
        u = a["unicode"]
        u = {"&amp;": "&", "&apos;": "'"}.get(u, u)
        u = re.sub(r"&#x([0-9a-fA-F]+);", lambda g: chr(int(g.group(1), 16)), u)
        d = a.get("d", "")
        if re.search(r"[A-KN-Za-kn-z]", d):  # curves (a few accented glyphs): not needed
            continue
        glyphs[u] = [round(float(a["horiz-adv-x"])), polylines(d, lambda x: x - SHIFT, lambda y: y)]
    raw = json.loads((pkg / "hersheytext.json").read_text())

    def rawglyph(font: str, ch: str) -> list:
        c = raw[font]["chars"][ord(ch) - 33]
        return [round(2 * c["o"] * K), polylines(c["d"].replace(",", " "), lambda x: x * K, lambda y: (22 - y) * K)]

    for u, ch in GREEK.items():
        glyphs[u] = rawglyph("greek", ch)
    for u, (font, ch) in MATH.items():
        glyphs[u] = rawglyph(font, ch)
    for u in DROP:  # lower the bottom dot (and comma tail) onto the baseline
        glyphs[u][1] = [[v - 94 if i % 2 and min(pl[1::2]) < 200 else v for i, v in enumerate(pl)] for pl in glyphs[u][1]]
    for u, src in ALIAS.items():
        glyphs[u] = glyphs[src]
    glyphs[" "] = [378, []]
    glyphs[" "] = glyphs[" "]

    used = set()
    for f in glob.glob(str(ROOT / "data" / "*" / "traces" / "*.json")):
        for e in json.loads(Path(f).read_text()).get("elements", []):
            for s in e.get("shapes", []):
                if s.get("t") == "t":
                    used |= set(re.sub(r"[_^]\{|\}", "", str(s.get("s", ""))))
    missing = sorted(c for c in used if c not in glyphs)
    off = []
    for u, (adv, pls) in glyphs.items():
        xs = [v for pl in pls for v in pl[0::2]]
        if xs and abs((min(xs) + max(xs)) / 2 - adv / 2) > 150:
            off.append(f"{u}({(min(xs) + max(xs)) / 2 - adv / 2:+.0f})")
    print("glyphs with ink centre > 0.15 em from their advance centre:", " ".join(off) or "none")
    print(f"{len(glyphs)} glyphs; trace characters {len(used)}, missing {missing}")

    head = """// Single-stroke font for the plotter SVG export. Generated by pipeline/make_plot_font.py; do not edit.
// Units 1/1000 em, y up, baseline 0, cap height 662. glyph = [advance, [[x0, y0, x1, y1, ...], ...]].
// Glyph data: Hershey fonts via the hersheytext npm package 2.0.0 (MIT, Copyright (c) 2014 James T; EMS Hershey Sans
// 1-stroke by Windell H. Oskay, evilmadscientist.com; Hershey Greek, Math, Script).
// The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the U. S. National Bureau of Standards.
// The format of the Font data in this distribution was originally created by James Hurt, Cognition, Inc.,
// 900 Technology Park Drive, Billerica, MA 01821 (mit-eddie!ci-dandelion!hurt).
"""
    body = json.dumps({"cap": 662, "glyphs": glyphs}, ensure_ascii=False, separators=(",", ":"))
    out = ROOT / "viewer" / "plot-font.js"
    out.write_text(head + f"(typeof window !== 'undefined' ? window : globalThis).PlotFont = {body};\n")
    print(f"-> {out.relative_to(ROOT)} {out.stat().st_size / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
